#!/usr/bin/env bash
# Rewrites android/gradle/verification-metadata.xml, the list of hashes Gradle checks every download against.
# Run this after changing a Gradle dependency or plugin, including on a Dependabot pull request, then read the diff:
# only the packages you meant to change should move. Needs JAVA_HOME and ANDROID_HOME.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
metadata="$root/android/gradle/verification-metadata.xml"
cd "$root/android"
# Gradle records only what it downloads, so anything already in its cache would be left out and fail on a clean machine.
# Start from an empty cache and an empty list, which also takes a few minutes and drops what is no longer used.
GRADLE_USER_HOME="$(mktemp -d "${TMPDIR:-/tmp}/gradle-verification.XXXXXX")"
export GRADLE_USER_HOME
trap 'rm -rf "$GRADLE_USER_HOME"' EXIT
rm -f "$metadata"
# An empty host keeps this from replacing the build the LAN update server offers. Nothing here is signed or published.
PASSVAULT_DEV_UPDATE_HOST='' ./gradlew --console=plain --no-daemon --write-verification-metadata sha256 \
  clean :app:assembleDebug :app:testDebugUnitTest :app:lintDebug :app:assembleQa :app:assembleQaAndroidTest \
  :app:assembleRelease :app:lintRelease :app:bundlePlayRelease :app:assemblePlayRelease :app:lintPlayRelease

# Gradle records only what this computer downloaded, and aapt2 has a separate download per system. CI runs on Linux.
python3 - "$metadata" <<'PY'
import hashlib
import re
import sys
import urllib.request

path = sys.argv[1]
text = open(path).read()
for version in re.findall(r'<component group="com\.android\.tools\.build" name="aapt2" version="([^"]+)"', text):
    for system in ("linux", "osx"):
        name = f"aapt2-{version}-{system}.jar"
        if name in text:
            continue
        url = f"https://dl.google.com/dl/android/maven2/com/android/tools/build/aapt2/{version}/{name}"
        with urllib.request.urlopen(url, timeout=120) as response:
            digest = hashlib.sha256(response.read()).hexdigest()
        artifact = (f'         <artifact name="{name}">\n'
                    f'            <sha256 value="{digest}" origin="Generated by Gradle"/>\n'
                    '         </artifact>\n')
        anchor = f'<component group="com.android.tools.build" name="aapt2" version="{version}">\n'
        text = text.replace(anchor, anchor + artifact)
open(path, "w").write(text)
PY
printf 'Updated %s\n' "$metadata"
